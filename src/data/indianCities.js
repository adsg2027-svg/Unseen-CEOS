export function getStateFromCity(city) {
  if (!city || city.trim().length < 3) return '';
  const normalized = city.trim();
  const exactKey = Object.keys(CITY_TO_STATE).find(
    k => k.toLowerCase() === normalized.toLowerCase()
  );
  if (exactKey) return CITY_TO_STATE[exactKey];
  const partialKey = Object.keys(CITY_TO_STATE).find(
    k => k.toLowerCase().startsWith(normalized.toLowerCase())
  );
  if (partialKey) return CITY_TO_STATE[partialKey];
  return '';
}
